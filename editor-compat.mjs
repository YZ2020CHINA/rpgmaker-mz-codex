import { readFile, writeFile, rename, unlink, realpath, stat } from 'node:fs/promises';
import path from 'node:path';
import { randomUUID, createHash } from 'node:crypto';
import { TextDecoder } from 'node:util';

const HEADER = '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n';
const NAME = /^[^\\/\x00-\x1f<>:"|?*]+$/u;
const validName = name => typeof name === 'string' && NAME.test(name) && name.trim() === name && !['.', '..'].includes(name) && !/[. ]$/.test(name);
const contained = (root, file) => { const rel = path.relative(root, file); return rel === '' || (!rel.startsWith(`..${path.sep}`) && rel !== '..' && !path.isAbsolute(rel)); };
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
export function parsePluginManifest(source) {
  // Never evaluate game JavaScript to read configuration. Only a literal JSON array is accepted.
  const match = source.replace(/^\uFEFF/, '').match(/^\s*(?:(?:\/\/[^\r\n]*(?:\r?\n|$)|\/\*[\s\S]*?\*\/)\s*)*var\s+\$plugins\s*=\s*(\[[\s\S]*\])\s*;\s*$/);
  if (!match) throw new Error('plugins.js must contain only comments and var $plugins = <JSON array>; arbitrary JavaScript will not be executed or rewritten.');
  const entries = JSON.parse(match[1]);
  if (!Array.isArray(entries)) throw new Error('Plugin manifest must be an array.');
  const seen = new Set();
  for (const entry of entries) {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry) || !validName(entry.name)) throw new Error('Each plugin needs a safe basename without .js or directory separators.');
    if (/\.js$/i.test(entry.name)) throw new Error(`Plugin name must omit .js: ${entry.name}`);
    if (seen.has(entry.name.toLowerCase())) throw new Error(`Duplicate plugin name: ${entry.name}`);
    seen.add(entry.name.toLowerCase());
    if (typeof entry.status !== 'boolean' || typeof entry.description !== 'string') throw new Error(`Invalid status/description for plugin ${entry.name}.`);
    if (!entry.parameters || typeof entry.parameters !== 'object' || Array.isArray(entry.parameters) || Object.values(entry.parameters).some(v => typeof v !== 'string')) throw new Error(`Plugin parameters must be string-valued: ${entry.name}`);
  }
  return entries;
}
export function serializePluginManifest(entries) {
  // MZ emits the assignment on its own line, then a JSON array with one record per line.
  const source = `${HEADER}[\n${entries.map(entry => JSON.stringify(entry)).join(',\n')}\n];\n`;
  parsePluginManifest(source);
  return source;
}
export async function projectFile(root, relative) {
  const resolved = await realpath(path.join(root, relative));
  if (!contained(root, resolved)) throw new Error(`Project file escapes project root: ${relative}`);
  if (!(await stat(resolved)).isFile()) throw new Error(`Expected a file: ${relative}`);
  return resolved;
}
async function textFile(root, relative) {
  return new TextDecoder('utf-8', { fatal: true }).decode(await readFile(await projectFile(root, relative)));
}
export async function checkEditorProject(directory) {
  const root = await realpath(directory);
  const errors = [], warnings = [];
  const issue = (file, message) => errors.push({ file, message });
  for (const file of ['game.rmmzproject', 'data/System.json', 'data/MapInfos.json', 'js/main.js', 'js/rmmz_core.js', 'index.html', 'package.json']) {
    try {
      const source = await textFile(root, file);
      if (!source.trim()) throw new Error('File is empty.');
      if (file.endsWith('.json')) JSON.parse(source.replace(/^\uFEFF/, ''));
      if (file === 'game.rmmzproject' && !/^RPGMZ\s+\d+\.\d+\.\d+\s*$/.test(source)) throw new Error('Invalid MZ project marker.');
    } catch (e) { issue(file, e.message); }
  }
  let entries;
  try {
    const source = await textFile(root, 'js/plugins.js');
    entries = parsePluginManifest(source);
    if (!/^\/\/ Generated by RPG Maker\.\r?\n\/\/ Do not edit this file directly\.\r?\nvar \$plugins =\r?\n\[/.test(source.replace(/^\uFEFF/, ''))) {
      issue('js/plugins.js', 'Valid literal manifest, but not in native MZ editor layout. Use mz_update_plugin with no fields to normalize; syntax-only/playtest checks do not prove editor compatibility.');
    }
    for (const entry of entries.filter(e => e.status)) {
      try { if (!(await readFile(await projectFile(root, `js/plugins/${entry.name}.js`))).length) throw new Error('Enabled plugin script is empty.'); }
      catch (e) { issue(`js/plugins/${entry.name}.js`, e.message); }
    }
  } catch (e) { issue('js/plugins.js', e.message); }
  warnings.push('Static checks do not confirm that the editor loaded the project; process launch alone is not confirmation.');
  return { ok: errors.length === 0, projectPath: root, pluginCount: entries?.length ?? null, errors, warnings };
}
export async function updatePluginManifest(directory, args = {}, beforeWrite = async () => {}) {
  const root = await realpath(directory);
  const filename = await projectFile(root, 'js/plugins.js');
  const oldBytes = await readFile(filename);
  const entries = parsePluginManifest(new TextDecoder('utf-8', { fatal: true }).decode(oldBytes));
  const oldEntries = JSON.parse(JSON.stringify(entries));
  if (args.name !== undefined) {
    if (!validName(args.name) || /\.js$/i.test(args.name)) throw new Error('Use a plugin basename without .js or directory separators.');
    let entry = entries.find(e => e.name === args.name);
    if (!entry) {
      entry = { name: args.name, status: false, description: '', parameters: {} };
      entries.push(entry);
    }
    if (args.enabled !== undefined) entry.status = args.enabled;
    if (args.description !== undefined) entry.description = args.description;
    // Merge supplied parameter keys; do not discard existing plugin settings or reorder records.
    if (args.parameters !== undefined) entry.parameters = { ...entry.parameters, ...args.parameters };
  } else if (args.enabled !== undefined || args.description !== undefined || args.parameters !== undefined) {
    throw new Error('name is required when changing a plugin; omit all fields to normalize layout only.');
  }
  const source = serializePluginManifest(entries);
  for (const entry of entries.filter(e => e.status)) {
    const plugin = await projectFile(root, `js/plugins/${entry.name}.js`);
    if (!(await readFile(plugin)).length) throw new Error(`Enabled plugin script is empty: ${entry.name}`);
  }
  const changed = !oldBytes.equals(Buffer.from(source, 'utf8'));
  const result = { file: 'js/plugins.js', changed, previousSha256: hash(oldBytes), plugins: entries, previousPlugins: oldEntries };
  if (args.dryRun || !changed) return { ...result, dryRun: !!args.dryRun };
  // beforeWrite runs only after all validation; caller supplies a project checkpoint.
  const checkpoint = await beforeWrite();
  if (await projectFile(root, 'js/plugins.js') !== filename || !(await readFile(filename)).equals(oldBytes)) throw new Error('plugins.js changed during preparation. Re-read before retrying.');
  const temp = `${filename}.${randomUUID()}.tmp`;
  try {
    await writeFile(temp, source, { encoding: 'utf8', flag: 'wx' });
    if (!(await readFile(filename)).equals(oldBytes)) throw new Error('plugins.js changed before write. Re-read before retrying.');
    await rename(temp, filename);
  } finally { await unlink(temp).catch(e => { if (e.code !== 'ENOENT') throw e; }); }
  return { ...result, dryRun: false, checkpoint };
}
